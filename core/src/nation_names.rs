/// Traduz os nomes das nações de um banco ou save (os que ainda estão em inglês).
pub fn translate_nations(conn: &rusqlite::Connection) -> crate::Result<()> {
    let mut stmt = conn.prepare("UPDATE nations SET name = ?2 WHERE name = ?1")?;
    for (en, pt) in NATION_NAMES {
        stmt.execute([en, pt])?;
    }
    Ok(())
}

/// O nome do banco (em inglês) de um nome do jogo (o mesmo, se não estiver na lista).
pub fn nation_en(pt: &str) -> &str {
    NATION_NAMES.iter().find(|(_, p)| *p == pt).map_or(pt, |(e, _)| e)
}

/// O nome em português de um nome do banco (o mesmo, se não estiver na lista).
pub fn nation_pt(en: &str) -> &str {
    NATION_NAMES.iter().find(|(e, _)| *e == en).map_or(en, |(_, p)| p)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_bank_nation_has_a_name() {
        let Some(path) = crate::World::locate(std::path::Path::new(env!("CARGO_MANIFEST_DIR"))) else { return };
        let conn = rusqlite::Connection::open(path).unwrap();
        let names: Vec<String> = conn
            .prepare("SELECT name FROM nations")
            .unwrap()
            .query_map([], |r| r.get(0))
            .unwrap()
            .collect::<rusqlite::Result<_>>()
            .unwrap();
        let missing: Vec<&String> = names.iter().filter(|n| !NATION_NAMES.iter().any(|(e, p)| e == n || p == n)).collect();
        assert!(missing.is_empty(), "{missing:?}");
        assert_eq!(nation_pt("Netherlands"), "Países Baixos");
    }
}
